class FakeCargo:
    """Answers ``cargo metadata`` (full with dependencies, or ``--no-deps``)
    and records every other command."""

    host = "local"

    def __init__(self, root: Path, *, deps_fail: bool = False) -> None:
        self.root = root
        self.deps_fail = deps_fail
        self.argv: list[list[str]] = []

    def run(self, command: Command) -> Completed:
        argv = list(command.argv)
        self.argv.append(argv)
        if argv[:2] == ["cargo", "metadata"]:
            if "--no-deps" not in argv and self.deps_fail:
                return Completed(101, 0.0, 0.0, "local", "", None)
            body = full_metadata(str(self.root))
            if "--no-deps" in argv:
                body.pop("resolve")
            return Completed(0, 0.0, 0.0, "local", json.dumps(body))
        return Completed(0, 0.0, 0.0, "local", "")


def _git(cwd: Path, *args: str) -> str:
    return subprocess.run(
        ["git", *args], cwd=cwd, check=True, capture_output=True, text=True
    ).stdout.strip()


def _repo(tmp_path: Path, change: dict[str, str]) -> tuple[Path, str, str, list[str]]:
    repo = tmp_path / "repo"
    repo.mkdir()
    _git(repo, "init", "-q", "-b", "main")
    _git(repo, "config", "user.email", "t@example.com")
    _git(repo, "config", "user.name", "t")
    files = {
        "Cargo.toml": '[workspace]\nmembers = ["crates/*"]\n',
        "Cargo.lock": BASE_LOCK,
        "rust-toolchain.toml": '[toolchain]\nchannel = "1.90"\n',
    }
    for name, text in files.items():
        (repo / name).write_text(text)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "base")
    base = _git(repo, "rev-parse", "HEAD")
    for name, text in change.items():
        (repo / name).write_text(text)
    _git(repo, "add", "-A")
    _git(repo, "commit", "-q", "-m", "change")
    head = _git(repo, "rev-parse", "HEAD")
    changed = _git(repo, "diff", "--name-only", base, head).splitlines()
    return repo, base, head, changed


def _run(
    tmp_path: Path, change: dict[str, str], impact: Impact, **runner: Any
) -> tuple[Any, FakeCargo]:
    repo, base, head, changed = _repo(tmp_path, change)
    fake = FakeCargo(repo, **runner)
    ctx = StepContext(
        checkout=repo,
        base=base,
        head=head,
        branches=["a"],
        changed=changed,
        env={"PATH": "/usr/bin:/bin"},
        log_dir=tmp_path / "logs",
        prefix="01-",
        runner=fake,
        events=no_events,
    )
    return run_step(CargoTests(select=impact), ctx), fake


def test_a_lock_change_tests_the_members_using_its_changed_entries(
    tmp_path: Path,
) -> None:
    result, fake = _run(tmp_path, {"Cargo.lock": NEW_ITOA}, Impact())
    assert result.detail["selection"] == ["api", "bench", "cli", "core"]
    metadata = [argv for argv in fake.argv if argv[:2] == ["cargo", "metadata"]]
    assert metadata and "--no-deps" not in metadata[0]
    log = Path(result.log).read_text()
    assert "itoa 1.0.1" in log


@pytest.mark.parametrize(
    ("change", "impact", "runner"),
    [
        # The toolchain changed with the lock.
        ({"Cargo.lock": NEW_ITOA, "rust-toolchain.toml": '[toolchain]\nchannel = "1.91"\n'},
         Impact(roots=()), {}),
        # A [patch] in the workspace manifest.
        ({"Cargo.lock": NEW_ITOA,
          "Cargo.toml": '[workspace]\nmembers = ["crates/*"]\n[patch.crates-io]\nitoa = { path = "x" }\n'},
         Impact(roots=()), {}),
        # A lock that does not parse.
        ({"Cargo.lock": "[[package]\n"}, Impact(), {}),
        # The resolved graph cannot be read.
        ({"Cargo.lock": NEW_ITOA}, Impact(), {"deps_fail": True}),
        # Asked for: the lock as a whole, or the lock as a root.
        ({"Cargo.lock": NEW_ITOA}, Impact(lockfile="all"), {}),
        ({"Cargo.lock": NEW_ITOA}, Impact(roots=("Cargo.lock",)), {}),
    ],
)  # fmt: skip
def test_a_lock_change_still_tests_everything_when_in_doubt(
    tmp_path: Path, change: dict[str, str], impact: Impact, runner: dict[str, Any]
) -> None:
    result, _fake = _run(tmp_path, change, impact, **runner)
    assert result.detail["selection"] == "all"
