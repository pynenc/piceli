def test_lock_diff_names_the_changed_and_added_entries() -> None:
    assert lock_diff(BASE_LOCK, BASE_LOCK) == set()
    assert lock_diff(BASE_LOCK, NEW_ITOA) == {("itoa", "1.0.1")}
    # A changed checksum or dependency list is a changed entry too.
    resummed = BASE_LOCK.replace('checksum = "rand0.8.0"', 'checksum = "other"')
    assert lock_diff(BASE_LOCK, resummed) == {("rand", "0.8.0")}
    # An entry only removed changes the entries that listed it.
    dropped = BASE_LOCK.replace(' "rand",\n', "")
    assert lock_diff(BASE_LOCK, dropped) == {("other", "0.1.0")}


@pytest.mark.parametrize(
    ("before", "after"),
    [
        (BASE_LOCK, "this is [not toml"),
        (None, BASE_LOCK),
        (BASE_LOCK, BASE_LOCK + '\n[[patch.unused]]\nname = "x"\nversion = "1.0.0"\n'),
    ],
)
def test_lock_diff_selects_everything_when_in_doubt(
    before: str | None, after: str | None
) -> None:
    assert isinstance(lock_diff(before, after), str)


def test_changed_entries_select_the_members_that_use_them_transitively() -> None:
    meta = full_metadata("/w")
    users = lock_users({("itoa", "1.0.1")}, meta)
    # core reaches itoa through serde, api and cli through core; bench links
    # core in its tests. other does not use it.
    assert sorted(users) == ["api", "bench", "cli", "core"]
    assert users["cli"] == "uses itoa 1.0.1 (Cargo.lock entry changed)"
    assert users["bench"].startswith("its tests use")
    why: list[str] = []
    chosen = select(
        ["Cargo.lock"], meta, (), why.append, lockfile="packages", lock_users=users
    )
    assert chosen == ["api", "bench", "cli", "core"]
    assert any("itoa 1.0.1" in line for line in why)
    # A dev-dependency changed: only the member whose tests use it.
    assert sorted(lock_users({("rand", "0.8.0")}, meta)) == ["other"]
    # The lock as a whole: everything.
    assert select(["Cargo.lock"], meta, (), lockfile="all") is None


@pytest.mark.parametrize(
    ("files", "outside", "expected"),
    [
        (["scripts/fitness.sh"], "all", None),
        (["scripts/fitness.sh"], "none", []),
        (["README.md", "docs/guide/x.txt", "crates/core/README.md"], "all", ["api", "bench", "cli", "core"]),
        (["README.md", "docs/x.md"], "all", []),
    ],
)  # fmt: skip
def test_files_outside_every_package(
    files: list[str], outside: str, expected: list[str] | None
) -> None:
    meta = full_metadata("/w")
    assert select(files, meta, (), outside=outside, ignore=Impact().ignore) == expected


def test_impact_declaration_and_its_defaults() -> None:
    impact = Impact()
    assert (impact.lockfile, impact.outside) == ("packages", "all")
    assert "Cargo.lock" not in impact.roots
    assert impact.ignore == ("*.md", "docs/*")
    custom = Impact(lockfile="all", outside="none", ignore=["*.txt"])
    train = Train("t", steps=[CargoTests(select=custom)])
    assert Train.from_dict(json.loads(json.dumps(train.to_dict()))) == train
    from piceli.train import TrainError

    with pytest.raises(TrainError, match="lockfile"):
        Impact(lockfile="some")  # type: ignore[arg-type]
    with pytest.raises(TrainError, match="outside"):
        Impact(outside="maybe")  # type: ignore[arg-type]


