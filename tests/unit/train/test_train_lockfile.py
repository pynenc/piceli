"""Impact selection of a ``Cargo.lock`` change, and of files outside every
package: the lock's changed entries select the members that use them."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path
from typing import Any

import pytest

from piceli.train import CargoTests, Impact, Train
from piceli.train.impact import lock_diff, lock_users, select
from piceli.train.runner import Command, Completed, no_events
from piceli.train.steps import StepContext, run_step

REGISTRY = "registry+https://github.com/rust-lang/crates.io-index"


def lock(*packages: tuple[str, str, list[str]], extra: str = "") -> str:
    """A ``Cargo.lock`` of ``(name, version, dependencies)``; a member has no
    source."""
    parts = ["# generated by cargo\nversion = 4\n"]
    for name, version, deps in packages:
        member = name in {"core", "api", "cli", "bench", "other"}
        source = (
            "" if member else f'source = "{REGISTRY}"\nchecksum = "{name}{version}"\n'
        )
        listed = "".join(f' "{d}",\n' for d in deps)
        parts.append(
            f'\n[[package]]\nname = "{name}"\nversion = "{version}"\n{source}'
            + (f"dependencies = [\n{listed}]\n" if deps else "")
        )
    return "".join(parts) + extra


BASE_LOCK = lock(
    ("api", "0.1.0", ["core"]),
    ("bench", "0.1.0", ["core"]),
    ("cli", "0.1.0", ["api"]),
    ("core", "0.1.0", ["serde"]),
    ("itoa", "1.0.0", []),
    ("other", "0.1.0", ["rand"]),
    ("rand", "0.8.0", []),
    ("serde", "1.0.1", ["itoa"]),
)
NEW_ITOA = BASE_LOCK.replace(
    '"itoa"\nversion = "1.0.0"', '"itoa"\nversion = "1.0.1"'
).replace("itoa1.0.0", "itoa1.0.1")


def full_metadata(root: str, itoa: str = "1.0.1") -> dict[str, Any]:
    """``cargo metadata`` with the resolved graph: members core, api (uses
    core), cli (uses api), bench (core as a dev-dependency), other (rand as
    a dev-dependency); core uses serde, which uses itoa."""

    def member(name: str, deps: list[tuple[str, str | None]]) -> dict[str, Any]:
        return {
            "id": f"path+file://{root}/crates/{name}#{name}@0.1.0",
            "name": name,
            "version": "0.1.0",
            "manifest_path": f"{root}/crates/{name}/Cargo.toml",
            "dependencies": [
                {"name": d, "kind": k, "path": f"{root}/crates/{d}"} for d, k in deps
            ],
        }

    def external(name: str, version: str) -> dict[str, Any]:
        return {
            "id": f"{REGISTRY}#{name}@{version}",
            "name": name,
            "version": version,
            "manifest_path": f"/registry/{name}-{version}/Cargo.toml",
            "dependencies": [],
        }

    members = [
        member("core", []),
        member("api", [("core", None)]),
        member("cli", [("api", None)]),
        member("bench", [("core", "dev")]),
        member("other", []),
    ]
    externals = [
        external("serde", "1.0.1"),
        external("itoa", itoa),
        external("rand", "0.8.0"),
    ]
    ids = {p["name"]: p["id"] for p in members + externals}

    def node(name: str, *deps: tuple[str, str | None]) -> dict[str, Any]:
        return {
            "id": ids[name],
            "deps": [
                {"name": d, "pkg": ids[d], "dep_kinds": [{"kind": k, "target": None}]}
                for d, k in deps
            ],
        }

    return {
        "workspace_root": root,
        "workspace_members": [p["id"] for p in members],
        "packages": members + externals,
        "resolve": {
            "nodes": [
                node("core", ("serde", None)),
                node("api", ("core", None)),
                node("cli", ("api", None)),
                node("bench", ("core", "dev")),
                node("other", ("rand", "dev")),
                node("serde", ("itoa", None)),
                node("itoa"),
                node("rand"),
            ]
        },
    }


