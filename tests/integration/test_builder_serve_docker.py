"""Opt-in: a build host builds a wanted build for every platform (0.21.0).

Builds the builder image from this checkout (as ``test_builder_image``),
starts a throwaway registry on the loopback, and serves one wanted build of
a small Rust component for linux/amd64 and linux/arm64 with the real
``piceli builder serve`` machinery: the source exported with Git, built in
the builder image on this machine's engine (the other architecture
cross-compiled with cargo zigbuild), both archives pushed and one OCI index
over them. The answer it posts holds the index. The registry container and
the images go at the end::

    PICELI_IMAGE_TESTS=1 uv run pytest tests/integration/test_builder_serve_docker.py
"""

