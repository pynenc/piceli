def _git(path: Path, *args: str) -> str:
    return subprocess.run(
        ["git", "-C", str(path), *args], check=True, capture_output=True, text=True
    ).stdout.strip()


def test_a_build_host_builds_every_platform_and_pushes_one_index(
    builder_image: str,
    registry: int,
    tmp_path: Path,
) -> None:
    from piceli.dev.hosts import ContainerCli
    from piceli.dev.model import BuildHost
    from piceli.gitops.state import DirectoryChannel
    from piceli.infra.builder_serve import BuilderServe, docker_container, prepare_cache
    from piceli.pipeline.backend import Backend, RegistryRoute

    app = tmp_path / "app"
    (app / "crates" / "hello" / "src").mkdir(parents=True)
    (app / "piceli.toml").write_text(CONTRACT)
    (app / "crates" / "hello" / "Cargo.toml").write_text(
        '[package]\nname = "hello"\nversion = "0.1.0"\nedition = "2021"\n'
    )
    (app / "crates" / "hello" / "src" / "main.rs").write_text(
        'fn main() { println!("hi"); }\n'
    )
    (app / "crates" / "hello" / "Cargo.lock").write_text(
        "# This file is automatically @generated by Cargo.\n"
        "# It is not intended for manual editing.\n"
        "version = 4\n\n"
        '[[package]]\nname = "hello"\nversion = "0.1.0"\n'
    )
    _git(app, "init", "-q", "-b", "main")
    _git(app, "-c", "user.email=t@x", "-c", "user.name=t", "add", "-A")
    _git(app, "-c", "user.email=t@x", "-c", "user.name=t", "commit", "-qm", "hello")
    commit = _git(app, "rev-parse", "HEAD")
    channel = DirectoryChannel(tmp_path / "controller")
    wanted = {
        "id": "a" * 20,
        "kind": "components",
        "components": [
            {"component": "hello", "source": "app", "commit": commit,
             "digest": "sha256:" + "5" * 64, "repository": "shop/hello"},
        ],
        "urls": {"app": str(app)},
        "platforms": ["linux/amd64", "linux/arm64"],
        "images": ["hello"],
        "claimed": {"host": "laptop"},
    }  # fmt: skip
    channel.publish({"controller": {"builds_wanted": [wanted]}})
    host = BuildHost.docker("laptop")
    cli = ContainerCli(host)
    volume = f"piceli-build-cache-test-{uuid.uuid4().hex[:8]}"
    route = RegistryRoute(
        push=f"127.0.0.1:{registry}", node_registry=f"127.0.0.1:{registry}", tls=False
    )
    backend = Backend()
    lines: list[str] = []
    try:
        prepare_cache(cli, builder_image, volume)

        def push(image_id: str, repository: str, archive: Path) -> str:
            delivered: dict[str, Any] = backend.registry_deliver(
                route, image_id, repository, archive=archive
            )
            assert delivered.get("state") == "succeeded", delivered
            return str(delivered["pull_ref"])

        began = time.monotonic()
        worker = BuilderServe(
            host="laptop",
            image=builder_image,
            channel=channel,
            container=docker_container(cli, builder_image, volume),
            push=push,
            index=lambda repository, digests: backend.registry_index(
                route, repository, digests
            ),
            root=tmp_path / "builder",
            say=lines.append,
        )
        assert worker.once() == "a" * 20, "\n".join(lines[-40:])
        seconds = time.monotonic() - began
    finally:
        subprocess.run(
            ["docker", "volume", "rm", "-f", volume], capture_output=True, check=False
        )
    answers = list(channel.requests().values())
    failed = [b for b in answers if b["kind"] == "build-failed"]
    assert not failed, failed[0]["reason"] + "\n" + failed[0]["log_tail"][-3000:]
    (built,) = [b for b in answers if b["kind"] == "built"]
    image = built["images"]["hello"]
    assert sorted(image["platforms"]) == ["linux/amd64", "linux/arm64"]
    digest = image["manifest_digest"]
    assert image["pull_ref"] == f"127.0.0.1:{registry}/shop/hello@{digest}"
    request = urllib.request.Request(
        f"http://127.0.0.1:{registry}/v2/shop/hello/manifests/{digest}",
        headers={"Accept": "application/vnd.oci.image.index.v1+json"},
    )
    with urllib.request.urlopen(request, timeout=10) as reply:
        index = json.loads(reply.read())
    assert sorted(
        f"{m['platform']['os']}/{m['platform']['architecture']}"
        for m in index["manifests"]
    ) == ["linux/amd64", "linux/arm64"]
    print(f"\nbuilder serve: two platforms built and delivered in {seconds:.0f}s")


