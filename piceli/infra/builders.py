"""Building components and mirroring third-party images, one component at a time.

A component's ``build`` becomes a host build (:mod:`piceli.artifacts.host_build`,
no container VM) generated by :func:`host_build_document`:

- ``rust``: ``cargo zigbuild --release --locked`` of the crate's binary for
  the node's architecture (tools ``cargo``, ``cargo-zigbuild``, ``zig``),
  the binary at ``/usr/local/bin/<bin>`` and the entrypoint;
- ``python``: the package directory at ``/app/<dir>`` (byte-compiled with
  ``python3``), ``python3 -m <module>`` as the entrypoint;
- ``files``: the listed files and directories at their image paths (the
  tool ``true`` stands for "nothing to compile");
- ``dockerfile``: refused (``component-build-unsupported``): it needs a
  Docker engine, which neither the build Job nor the controller has.

Two builders run them and push each image by digest into the composition's
registry, returning the pull reference nodes use:

- :class:`LocalBuilder` builds on this machine (a laptop, a CI runner or a
  test) from a checkout of the source at its commit;
- :class:`JobBuilder` runs one Kubernetes Job on the builder node that
  fetches every source it needs at its resolved commit (one Git Secret for
  all) and builds every changed component (``piceli build job-run
  --component``), like the 0.13 cluster build.

Importing this module is side-effect free.
"""

from __future__ import annotations

import hashlib
import json
import re
import tempfile
import time
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Protocol

from piceli.infra import CompositionError
from piceli.infra.contract import ComponentContract

HOST_BUILD_REVISION = "piceli.host-build.v1"
_STAGE = "src"


def _unsupported(name: str, kind: str) -> CompositionError:
    return CompositionError(
        "component-build-unsupported",
        f"component {name!r}: a {kind} build needs a Docker engine; use a rust, "
        "python or files build",
    )


def host_build_document(
    name: str, contract: ComponentContract, source_root: Path, repository: str
) -> dict[str, Any]:
    """The ``host-build.toml`` (as a dict) that builds ``contract``'s image.

    :param source_root: The source's checkout (the build's paths are scanned
        in it to tell files from directories).
    :param repository: The image repository (``<prefix>/<component>``).
    """
    recipe = contract.build
    if recipe is None:
        raise CompositionError(
            "component-contract-invalid", f"component {name!r} has no build"
        )
    if recipe.kind == "dockerfile":
        raise _unsupported(name, recipe.kind)

    def include(path: str) -> list[str]:
        found = source_root.joinpath(*path.split("/"))
        return [f"{path}/**"] if found.is_dir() else [path]

    image = contract.image
    out: dict[str, Any] = {
        "name": name,
        "repository": repository,
        "user": f"{image.uid}:{image.gid}",
    }
    if image.base is not None:  # else ``scratch`` (a files build only)
        out["base"] = {"image": image.base, "digest": image.digest}
    if image.dirs:
        out["dirs"] = {
            path: f"{image.uid}:{image.gid}:{mode}" for path, mode in image.dirs
        }
    if image.workdir is not None:
        out["workdir"] = image.workdir
    globs = [glob for path in recipe.paths for glob in include(path)]
    build: dict[str, Any]
    if recipe.kind == "rust":
        command = [
            "cargo", "zigbuild", "--release", "--locked",
            "--target", "{rust_arch}-unknown-linux-gnu",
            "--manifest-path", f"{_STAGE}/{recipe.path}/Cargo.toml",
            "--bin", str(recipe.bin),
        ]  # fmt: skip
        if recipe.features:
            command += ["--features", ",".join(recipe.features)]
        build = {
            "tools": ["cargo", "cargo-zigbuild", "zig"],
            "commands": [command],
            "env": {"CARGO_TERM_COLOR": "never", "CARGO_INCREMENTAL": "0"},
        }
        binary = f"/usr/local/bin/{recipe.bin}"
        out["target_files"] = {
            f"{{rust_arch}}-unknown-linux-gnu/release/{recipe.bin}": binary
        }
        out["entrypoint"] = [binary]
    elif recipe.kind == "python":
        build = {
            "tools": ["python3"],
            "commands": [
                ["python3", "-m", "compileall", "-q", f"{_STAGE}/{recipe.path}"]
            ],
        }
        out["files"] = {f"{_STAGE}/{recipe.path}": f"/app/{recipe.path}"}
        out["entrypoint"] = ["python3", "-m", str(recipe.module)]
        out["env"] = {"PYTHONPATH": "/app"}
    else:
        build = {"tools": ["true"], "commands": [["true"]]}
        out["files"] = {f"{_STAGE}/{src}": dest for src, dest in recipe.files}
    if image.cmd is not None:
        out["cmd"] = list(image.cmd)
    return {
        "revision": HOST_BUILD_REVISION,
        "name": name,
        "build": {**build, "timeout_seconds": 1800},
        "context": {
            _STAGE: {
                "path": ".",
                "include": globs,
                "max_files": 100_000,
                "max_bytes": 1024 * 1024 * 1024,
            }
        },
        "output": {"image": [out]},
    }


@dataclass(frozen=True)
class BuildItem:
    """One component to build: its source at a commit and its digest."""

    component: str
    source: str
    commit: str
    digest: str
    contract: ComponentContract
    repository: str

    def describe(self) -> dict[str, Any]:
        return {
            "component": self.component,
            "source": self.source,
            "commit": self.commit,
            "digest": self.digest,
            "repository": self.repository,
        }


@dataclass(frozen=True)
class MirrorItem:
    """One third-party image to copy into the registry (``ref@pin``)."""

    component: str
    reference: str
    repository: str


@dataclass
class BuiltImage:
    """Where nodes pull a built or mirrored image from."""

    pull_ref: str
    manifest_digest: str
    extra: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "pull_ref": self.pull_ref,
            "manifest_digest": self.manifest_digest,
            **self.extra,
        }


class Builder(Protocol):
    """Builds components and mirrors images into the composition's registry."""

    def build(
        self, items: Sequence[BuildItem], checkout: Callable[[str, str, Path], Any]
    ) -> dict[str, BuiltImage]: ...

    def mirror(self, items: Sequence[MirrorItem]) -> dict[str, BuiltImage]: ...


def _pinned(receipt: Mapping[str, Any], what: str) -> BuiltImage:
    if receipt.get("state") != "succeeded" or not receipt.get("pull_ref"):
        raise CompositionError(
            "component-build-failed",
            f"{what}: delivery ended {receipt.get('result') or receipt.get('state')} "
            f"({receipt.get('reason')})",
        )
    ref = str(receipt["pull_ref"])
    return BuiltImage(ref, ref.rsplit("@", 1)[-1])


class LocalBuilder:
    """Build on this machine; push through a route to the registry.

    :param route: How this machine reaches the registry
        (:class:`piceli.pipeline.backend.RegistryRoute`).
    :param platform: The nodes' platform (``linux/amd64`` or ``linux/arm64``).
    :param cache_dir: The host build cache (stage, target, blobs).
    :param work_dir: Where checkouts and archives go (removed after each build).
    :param backend: :class:`piceli.pipeline.backend.Backend` (tests: a fake).
    """

    def __init__(
        self,
        route: Any,
        *,
        platform: str,
        cache_dir: Path,
        work_dir: Path,
        backend: Any = None,
        say: Callable[[str], None] = lambda _: None,
    ) -> None:
        self.route = route
        self.platform = platform
        self.cache_dir = cache_dir
        self.work_dir = work_dir
        self.backend = backend
        self.say = say

    def _backend(self) -> Any:
        if self.backend is None:
            from piceli.pipeline.backend import Backend

            self.backend = Backend()
        return self.backend

    def build(
        self, items: Sequence[BuildItem], checkout: Callable[[str, str, Path], Any]
    ) -> dict[str, BuiltImage]:
        from piceli.artifacts.build_spec import BuildSpecError
        from piceli.artifacts.host_build import HostBuildGrant, HostBuildSpec
        from piceli.artifacts.node_facts import NodeFacts

        built: dict[str, BuiltImage] = {}
        facts = NodeFacts.for_platform(self.platform)
        self.work_dir.mkdir(parents=True, exist_ok=True)
        for item in items:
            self.say(f"[build] {item.component} from {item.source}@{item.commit[:12]}")
            with (
                checkout(item.source, item.commit, self.work_dir) as tree,
                tempfile.TemporaryDirectory(prefix="out-", dir=self.work_dir) as out,
            ):
                document = host_build_document(
                    item.component, item.contract, Path(tree), item.repository
                )
                try:
                    spec = HostBuildSpec.from_dict(document, Path(tree))
                    spec = spec.for_node(facts).with_cache_dir(self.cache_dir)
                    plan = spec.plan()
                    grant = HostBuildGrant(plan.plan_hash, time.time() + 3600)
                    receipt = spec.run(grant, Path(out), progress=self.say).to_dict()
                except BuildSpecError as error:
                    raise CompositionError(
                        "component-build-failed",
                        f"component {item.component!r}: host build failed ({error.code})",
                    ) from None
                entry = receipt["outputs"]["images"][item.component]
                delivered = self._backend().registry_deliver(
                    self.route,
                    entry["image_id"],
                    item.repository,
                    archive=Path(out) / entry["archive"],
                )
                built[item.component] = _pinned(delivered, item.component)
        return built

    def mirror(self, items: Sequence[MirrorItem]) -> dict[str, BuiltImage]:
        done: dict[str, BuiltImage] = {}
        for item in items:
            self.say(f"[mirror] {item.component}: {item.reference}")
            receipt = self._backend().mirror_deliver(
                self.route,
                item.reference,
                item.repository,
                platform=None,  # the whole index: pulled by its digest
                credentials=None,
            )
            done[item.component] = _pinned(receipt, item.component)
        return done

    def build_spec(
        self, request: Any, checkout: Callable[[str, str, Path], Any]
    ) -> dict[str, BuiltImage]:
        """Build a pipeline's host spec from checkouts of its sources; push the changed images.

        ``request`` is a :class:`piceli.infra.pipelines.SpecBuildRequest`.
        """
        from contextlib import ExitStack

        from piceli.infra.pipelines import run_spec_build

        self.work_dir.mkdir(parents=True, exist_ok=True)

        def deliver(name: str, archive: Path, image_id: str, repository: str) -> Any:
            return self._backend().registry_deliver(
                self.route, image_id, repository, archive=archive
            )

        with (
            ExitStack() as stack,
            tempfile.TemporaryDirectory(prefix="out-", dir=self.work_dir) as out,
        ):
            roots = {
                name: Path(stack.enter_context(checkout(name, commit, self.work_dir)))
                for name, commit in sorted(request.commits.items())
            }
            self.say(f"[build] {request.spec}: " + ", ".join(sorted(request.images)))
            receipt = run_spec_build(
                request,
                roots,
                platforms=(self.platform,),
                cache=self.cache_dir,
                out=Path(out),
                deliver=deliver,
                say=self.say,
            )
        return {
            name: BuiltImage(str(entry["pull_ref"]), str(entry["manifest_digest"]))
            for name, entry in receipt["images"].items()
        }


