"""Render the NixOS module that installs the host agent (0.24.0).

``piceli host module MODULE:ATTR`` writes one self-contained ``.nix`` file:
the agent (:mod:`piceli.hosts.agent`) and its verifier
(:mod:`piceli.dev.nix_verify`) as strings, the host's configuration as JSON
(no secret), a systemd oneshot service and its timer, and the
``piceli-host-agent`` command (``pin``, ``unpin``, ``rollback``) on the
system's PATH for ``piceli host`` over SSH. The user commits it
next to the host's configuration and imports it; Piceli never edits the
flake. Because the agent is part of the system it switches to, every
release carries the agent of the Piceli that rendered the module.

Importing this module is side-effect free.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from piceli.hosts.model import NixHost, agent_config

__all__ = ["nix_string", "render_module"]


def nix_string(text: str) -> str:
    """``text`` as a double-quoted Nix string (``\\``, ``"`` and ``${`` escaped)."""
    return (
        '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("${", "\\${") + '"'
    )


def _source(module: Any) -> str:
    return Path(module.__file__).read_text(encoding="utf-8")


def render_module(host: NixHost, ref: str, version: str | None = None) -> str:
    """The NixOS module of ``host`` (``ref``: the ``MODULE:ATTR`` it came from)."""
    from piceli.dev import nix_verify
    from piceli.hosts import agent

    if version is None:
        from piceli import __version__ as version
    config = json.dumps(agent_config(host), sort_keys=True, indent=2)
    follow = host.follow.describe()
    following = (
        f"tags {follow['pattern']}"
        if follow["kind"] == "tag"
        else f"branch {follow['name']}"
    )
    return f"""# The Piceli host agent of {host.name} (piceli {version}).
# Generated by `piceli host module {ref}`: regenerate it, do not edit it.
# Import it from the host's NixOS configuration. The agent follows
# {following} of build {host.build} in {host.cache.store_url},
# never builds on the host, and writes {agent_config(host)["state_dir"]}/status.json.
{{ config, lib, pkgs, ... }}:
let
  settings = builtins.fromJSON {nix_string(config)};
  configFile = pkgs.writeText "piceli-host.json" (builtins.toJSON (settings // {{
    system = pkgs.stdenv.hostPlatform.system;
    tools = {{
      nix = "${{config.nix.package}}/bin/nix";
      nix_env = "${{config.nix.package}}/bin/nix-env";
      nix_store = "${{config.nix.package}}/bin/nix-store";
      systemctl = "${{config.systemd.package}}/bin/systemctl";
    }};
  }}));
  agentSource = {nix_string(_source(agent))};
  verifySource = {nix_string(_source(nix_verify))};
  agent = pkgs.runCommand "piceli-host-agent" {{ }} ''
    mkdir -p $out
    cp ${{pkgs.writeText "piceli_host_agent.py" agentSource}} $out/piceli_host_agent.py
    cp ${{pkgs.writeText "nix_verify.py" verifySource}} $out/nix_verify.py
  '';
  # `piceli host pin|unpin|rollback` run it over SSH; the timer runs a poll.
  command = pkgs.writeShellScriptBin "piceli-host-agent" ''
    exec ${{pkgs.python3}}/bin/python3 -E -s ${{agent}}/piceli_host_agent.py --config ${{configFile}} "$@"
  '';
in
{{
  environment.systemPackages = [ command ];
  # The agent keeps {host.generations} system generations; the boot menu lists as many.
  boot.loader.grub.configurationLimit = lib.mkDefault {host.generations};
  boot.loader.systemd-boot.configurationLimit = lib.mkDefault {host.generations};
  systemd.services.piceli-host-agent = {{
    description = "Piceli host agent: follow {following} of {host.build}";
    wants = [ "network-online.target" ];
    after = [ "network-online.target" ];
    # The switch it runs never restarts or stops it.
    restartIfChanged = false;
    stopIfChanged = false;
    serviceConfig = {{
      Type = "oneshot";
      ExecStart = "${{command}}/bin/piceli-host-agent";
      StateDirectory = "piceli-host";
      StateDirectoryMode = "0755";
      TimeoutStartSec = "3h";
    }};
  }};
  systemd.timers.piceli-host-agent = {{
    wantedBy = [ "timers.target" ];
    timerConfig = {{
      OnBootSec = "1min";
      OnUnitInactiveSec = "{host.poll_seconds}s";
      RandomizedDelaySec = "30s";
    }};
  }};
}}
"""
